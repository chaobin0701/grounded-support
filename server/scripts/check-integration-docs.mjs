// Read-only live UI check: no fixture writes, model requests or persisted credentials.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import pg from 'pg';
import { JwtService } from '@nestjs/jwt';

if (!process.env.PLAYWRIGHT_MODULE_PATH) throw new Error('PLAYWRIGHT_MODULE_PATH required');
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE_PATH);
const pool = new pg.Pool({ host: '127.0.0.1', port: Number(process.env.POSTGRES_PORT || 5433), user: process.env.POSTGRES_USER, password: process.env.POSTGRES_PASSWORD, database: process.env.POSTGRES_DB || 'grounded_support' });
const base = 'http://localhost:8848';
const output = fileURLToPath(new URL('../../output/playwright/', import.meta.url));
const source = await readFile(new URL('../../web/src/docs/integration.md', import.meta.url), 'utf8');
let browser;
try {
  await mkdir(output, { recursive: true });
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const publicContext = await browser.newContext({ viewport: { width: 1440, height: 950 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const docs = await publicContext.newPage();
  const errors = [];
  docs.on('pageerror', error => errors.push(error.message));
  await docs.goto(`${base}/docs/integration`);
  await docs.getByRole('heading', { name: 'Agent 接入文档', exact: true }).waitFor();
  assert.equal(await docs.getByRole('navigation', { name: '文档目录', exact: true }).getByRole('link').count(), 11);
  await docs.screenshot({ path: output + 'integration-docs-desktop.png' });
  await docs.getByRole('button', { name: '复制文档', exact: true }).click();
  await docs.getByRole('status').filter({ hasText: '接入文档已复制' }).waitFor();
  assert.equal(await docs.evaluate(() => navigator.clipboard.readText()), source);
  const downloadPromise = docs.waitForEvent('download');
  await docs.getByRole('button', { name: '下载 Markdown', exact: true }).click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(), 'agent-integration.md');
  const bytes = [];
  for await (const chunk of await download.createReadStream()) bytes.push(chunk);
  assert.equal(Buffer.concat(bytes).toString('utf8'), source);
  await docs.getByRole('navigation', { name: '文档目录', exact: true }).getByRole('link', { name: 'SSE 流式回答', exact: true }).click();
  await docs.waitForURL('**/docs/integration#section-5');
  await docs.reload();
  await docs.waitForFunction(() => {
    const heading = document.getElementById('section-5');
    const rect = heading?.getBoundingClientRect();
    return rect && rect.top >= 72 && rect.top < 160;
  });
  await docs.screenshot({ path: output + 'integration-docs-sse.png' });
  await docs.setViewportSize({ width: 375, height: 812 });
  await docs.goto(`${base}/docs/integration`);
  await docs.getByRole('heading', { name: 'Agent 接入文档', exact: true }).waitFor();
  await docs.screenshot({ path: output + 'integration-docs-mobile.png' });
  assert.ok(await docs.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.querySelector('.integration-docs').scrollWidth <= innerWidth));
  await docs.getByText('文档目录', { exact: true }).click();
  await docs.getByRole('navigation', { name: '移动端文档目录', exact: true }).getByRole('link', { name: '每日配额与错误处理', exact: true }).click();
  assert.equal(await docs.locator('.docs-mobile-contents').getAttribute('open'), null);
  assert.ok(await docs.evaluate(() => document.documentElement.scrollWidth <= innerWidth));

  const actor = (await pool.query("SELECT a.id FROM admins a JOIN admin_roles ar ON ar.admin_id=a.id JOIN roles r ON r.id=ar.role_id WHERE r.code='super_admin' AND a.disabled_at IS NULL ORDER BY a.id LIMIT 1")).rows[0];
  assert.ok(actor);
  const signer = new JwtService({ secret: process.env.JWT_SECRET, signOptions: { issuer: process.env.JWT_ISSUER || 'grounded-support', audience: process.env.JWT_AUDIENCE || 'grounded-support-admin', expiresIn: 600 } });
  const token = await signer.signAsync({ sub: String(actor.id) });
  const me = await fetch(`${base}/api/admin/auth/me`, { headers: { Authorization: `Bearer ${token}` } }).then(response => response.json());
  assert.ok(me.permissionCodes.includes('integrations.read') || me.permissionCodes.includes('integrations.manage'));
  const adminContext = await browser.newContext({ viewport: { width: 1440, height: 950 }, permissions: ['clipboard-read', 'clipboard-write'] });
  await adminContext.addInitScript(session => localStorage.setItem('grounded-support.admin-session.v1', JSON.stringify(session)), { token, me, expiresAt: Date.now() + 600000 });
  const admin = await adminContext.newPage();
  admin.on('pageerror', error => errors.push(error.message));
  await admin.goto(`${base}/admin/integrations`);
  const card = admin.locator('.integration-card').first();
  await card.waitFor();
  const popupPromise = admin.waitForEvent('popup');
  await admin.getByRole('link', { name: /^接入文档/ }).click();
  const popup = await popupPromise;
  await popup.getByRole('heading', { name: 'Agent 接入文档', exact: true }).waitFor();
  assert.ok(popup.url().endsWith('/docs/integration'));
  await popup.close();
  const appId = await card.locator('code').textContent();
  await card.click();
  const dialog = admin.getByRole('dialog').first();
  await dialog.waitFor();
  assert.equal(await dialog.getByRole('navigation', { name: '接入应用面板', exact: true }).getByRole('button').count(), 3);
  assert.equal(await dialog.getByRole('button', { name: '接入示例', exact: true }).count(), 0);
  await dialog.getByRole('button', { name: '复制应用 ID', exact: true }).click();
  assert.equal(await admin.evaluate(() => navigator.clipboard.readText()), appId);
  await admin.locator('.toast-notice').filter({ hasText: '应用 ID已复制' }).waitFor();
  await admin.screenshot({ path: output + 'integration-app-docs-link.png' });
  await admin.setViewportSize({ width: 375, height: 812 });
  assert.ok(await admin.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log('Public documentation, shared Markdown copy/download, anchor restore, mobile layout, admin link and app-ID copy passed (read-only, no model calls).');
} finally {
  await browser?.close();
  await pool.end();
}
